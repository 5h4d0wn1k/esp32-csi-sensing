static uint8_t s_buf[SSD1306_W * SSD1306_H / 8];
static i2c_master_bus_handle_t s_bus;
static i2c_master_dev_handle_t s_dev;

static esp_err_t ssd1306_write_cmd(const uint8_t *cmds, size_t len)
{
    uint8_t tmp[32];
    if (len > sizeof(tmp) - 1) {
        return ESP_ERR_INVALID_SIZE;
    }
    tmp[0] = SSD1305_CTRL_CMD;
    memcpy(tmp + 1, cmds, len);
    return i2c_master_transmit(s_dev, tmp, len + 1, -1);
}

esp_err_t ssd1306_init(void)
{
    i2c_master_bus_config_t bus_cfg = {
        .i2c_port = SSD1306_I2C_PORT,
        .sda_io_num = CONFIG_OLED_SDA,
        .scl_io_num = CONFIG_OLED_SCL,
        .clk_source = I2C_CLK_SRC_DEFAULT,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = true,
    };
    ESP_RETURN_ON_ERROR(i2c_new_master_bus(&bus_cfg, &s_bus), TAG, "bus");

    i2c_device_config_t dev_cfg = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = CONFIG_OLED_I2C_ADDR,
        .scl_speed_hz = SSD1306_SCLK_HZ,
    };
    esp_err_t err = i2c_master_bus_add_device(s_bus, &dev_cfg, &s_dev);
    if (err != ESP_OK) {
        return err;
    }

    static const uint8_t init_cmds[] = {
        0xAE,                   /* display off */
        0xD5, 0x80,             /* clock divide / oscillator */
        0xA8, 0x3F,             /* multiplex ratio 64 */
        0xD3, 0x00,             /* display offset 0 */
        0x40,                   /* start line 0 */
        0x8D, 0x14,             /* charge pump on */
        0x20, 0x02,             /* page addressing mode */
        0xA1,                   /* segment remap */
        0xC8,                   /* COM scan direction */
        0xDA, 0x12,             /* COM pins */
        0x81, 0xCF,             /* contrast */
        0xD9, 0xF1,             /* precharge */
        0xDB, 0x40,             /* VCOM detect */
        0xA4,                   /* display from RAM */
        0xA6,                   /* normal (non-inverted) */
        0xAF,                   /* display on */
    };
    err = ssd1306_write_cmd(init_cmds, sizeof(init_cmds));
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "init cmds failed: %s", esp_err_to_name(err));
        return err;
    }
    ssd1306_clear();
    return ssd1306_display();
}

void ssd1306_clear(void)
{
    memset(s_buf, 0, sizeof(s_buf));
}

void ssd1306_draw_string(int x, int y, const char *str)
{
    if (y % 8 || y < 0 || y >= SSD1306_H) {
        return;
    }
    uint8_t *line = &s_buf[(y / 8) * SSD1306_W];
    while (*str) {
        uint8_t c = (uint8_t)*str++;
        if (c < 32 || c > 126) {
            c = '?';
        }
        const uint8_t *g = &s_font[(c - 32) * 5];
        for (int i = 0; i < 5 && x < SSD1306_W; i++, x++) {
            line[x] = g[i];
        }
        if (x < SSD1306_W) {
            line[x++] = 0x00;   /* inter-character gap */
        } else {
            break;
        }
    }
}

void ssd1306_invert(bool invert)
{
    const uint8_t cmd = invert ? 0xA7 : 0xA6;
    ssd1306_write_cmd(&cmd, 1);
}

esp_err_t ssd1306_display(void)
{
    for (int page = 0; page < SSD1306_H / 8; page++) {
        const uint8_t addr[] = {
            0xB0 | page,                    /* page address */
            0x00, 0x10,                     /* column 0 low/high nibble */
        };
        esp_err_t err = ssd1306_write_cmd(addr, sizeof(addr));
        if (err != ESP_OK) {
            return err;
        }
        uint8_t pkt[1 + SSD1306_W];
        pkt[0] = SSD1306_CTRL_DATA;
        memcpy(pkt + 1, &s_buf[page * SSD1306_W], SSD1306_W);
        err = i2c_master_transmit(s_dev, pkt, sizeof(pkt), -1);
        if (err != ESP_OK) {
            return err;
        }
    }
    return ESP_OK;
}

